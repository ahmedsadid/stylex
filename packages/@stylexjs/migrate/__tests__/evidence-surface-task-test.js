import fs from 'fs';
import path from 'path';
import {
  EVIDENCE_SURFACE_PROTOCOL_VERSION,
  RUNTIME_PROTOCOL_VERSION,
  initializeProject,
  loadVerificationCandidate,
  openEvidenceSurfaceTask,
  persistTestAssumption,
  saveInventory,
  scanRepository,
  submitContextAttempt,
  withGeneratedRuntimeProbeProviders,
} from '../src/index';
import { runCli } from '../src/cli';
import type { ProjectState, TestAssumption } from '../src/index';
import { createTempDir, createTempRepo, removeTempDir } from './utils/tempRepo';

function observation(color: string): $FlowFixMe {
  return {
    computedStyles: { card: { color } },
    dom: { card: { tagName: 'DIV', childCount: 0, text: 'Card' } },
    attributes: { card: { 'data-theme': 'dark' } },
    refs: { card: { attached: true, tagName: 'DIV' } },
    interactions: {},
  };
}

describe('generated evidence-surface tasks', () => {
  let repo: string;
  let workspaceRoot: string;
  let project: ProjectState;
  let assumption: TestAssumption;

  beforeEach(() => {
    repo = createTempRepo({
      'package.json': JSON.stringify({ private: true }),
      'src/Card.jsx': 'export const Card = () => <div>Card</div>;\n',
      'scripts/serve.cjs': 'require("http").createServer().listen(4173);\n',
    });
    workspaceRoot = createTempDir('stylex-migrate-evidence-surface-');
    project = initializeProject({ repositoryRoot: repo });
    const inventory = scanRepository({ repositoryRoot: repo });
    saveInventory(project, inventory);
    assumption = persistTestAssumption({
      project,
      input: {
        purpose: 'Exercise the exact dark card runtime case.',
        facts: [
          {
            statement: 'The disposable server exposes the selected card route.',
            status: 'inferred',
            inputFiles: ['src/Card.jsx'],
            detail: 'This is a test-only route assumption.',
          },
        ],
        scope: { files: ['src/Card.jsx'], cases: ['card-dark'] },
        rationale:
          'No repository-native runtime surface exists in the fixture.',
        alternatives: ['Add a repository-owned Playwright test.'],
        limitations: ['Covers one route and one viewport.'],
      },
      authorKind: 'agent',
      authoredBy: 'fixture-agent',
    });
  });

  afterEach(() => {
    removeTempDir(workspaceRoot);
    removeTempDir(repo);
  });

  function definition(): $FlowFixMe {
    return {
      protocolVersion: EVIDENCE_SURFACE_PROTOCOL_VERSION,
      packageRoot: '.',
      playwrightPackage: 'playwright',
      nativeSurfaceDisposition: 'none-known',
      server: {
        argv: ['node', 'scripts/serve.cjs'],
        cwd: '.',
        inputFiles: ['scripts/serve.cjs'],
        url: 'http://127.0.0.1:4173/',
        timeoutMs: 5000,
      },
      cases: [
        {
          id: 'card-dark',
          changePaths: ['src/Card.jsx'],
          siteIds: [],
          theme: 'dark',
          interaction: 'initial',
          viewport: { width: 800, height: 600, deviceScaleFactor: 1 },
          path: '/card',
          actions: [],
          targets: [
            {
              id: 'card',
              selector: '[data-runtime-target="card"]',
              computedProperties: ['color'],
              attributes: ['data-theme'],
            },
          ],
        },
      ],
      expectedObservations: {
        protocolVersion: RUNTIME_PROTOCOL_VERSION,
        cases: [{ id: 'card-dark', observation: observation('rgb(1, 2, 3)') }],
      },
      rationale:
        'Create a bounded fallback because discovery found no native surface.',
      limitations: [
        'The generated route does not prove application navigation.',
      ],
    };
  }

  test('locks generated bytes and automatically contributes a provider', () => {
    const opened = openEvidenceSurfaceTask({
      project,
      assumptionId: assumption.id,
      input: definition(),
      goal: 'Create the exact card-dark evidence surface.',
      workspaceRoot,
    });
    if (!opened.ok) throw new Error(opened.reasons.join('\n'));
    expect(opened.task).toMatchObject({
      origin: {
        kind: 'evidence-surface',
        assumptionArtifactHash: assumption.artifactHash,
        cases: [
          { id: 'card-dark', changePaths: ['src/Card.jsx'], siteIds: [] },
        ],
      },
      requiredOutputs: [
        { role: 'runtime-probe-collector', mutable: false },
        { role: 'runtime-probe-config', mutable: false },
      ],
    });
    const submitted = submitContextAttempt({
      project,
      taskId: opened.task.id,
      proposerKind: 'agent',
      proposerVersion: 'fixture-v1',
    });
    if (!submitted.ok) throw new Error(submitted.reasons.join('\n'));
    const evidenceSurface = loadVerificationCandidate(
      project,
      submitted.candidateId,
    );
    if (evidenceSurface == null) throw new Error('Missing evidence surface');
    const config = withGeneratedRuntimeProbeProviders({
      project,
      candidates: [evidenceSurface],
      subject: 'candidate',
      config: { concurrency: 1, outputPreviewBytes: 1024, providers: [] },
    });
    expect(config.providers).toHaveLength(1);
    expect(config.providers[0]).toMatchObject({
      kind: 'generated-runtime-probe',
      assumptionArtifactHash: assumption.artifactHash,
      expectedObservations: {
        cases: [{ id: 'card-dark', observation: observation('rgb(1, 2, 3)') }],
      },
    });
  });

  test('rejects mutation and requires an explicit disposition for known native surfaces', () => {
    const opened = openEvidenceSurfaceTask({
      project,
      assumptionId: assumption.id,
      input: definition(),
      goal: 'Create a fallback.',
      workspaceRoot,
    });
    if (!opened.ok) throw new Error(opened.reasons.join('\n'));
    fs.appendFileSync(
      path.join(
        opened.attempt.workspace.path,
        '.stylex-migrate-probes/runtime-probe.json',
      ),
      '{}',
    );
    expect(
      submitContextAttempt({
        project,
        taskId: opened.task.id,
        proposerKind: 'agent',
        proposerVersion: 'fixture-v1',
      }),
    ).toMatchObject({
      ok: false,
      reasons: [expect.stringContaining('modified')],
    });

    const nativeRepo = createTempRepo({
      'package.json': JSON.stringify({
        scripts: { e2e: 'playwright test' },
        devDependencies: { '@playwright/test': '1.0.0' },
      }),
      'playwright.config.js': 'module.exports = {};\n',
      'src/Card.jsx': 'export const Card = () => <div>Card</div>;\n',
      'scripts/serve.cjs': 'require("http").createServer().listen(4173);\n',
    });
    try {
      const nativeProject = initializeProject({ repositoryRoot: nativeRepo });
      const inventory = scanRepository({ repositoryRoot: nativeRepo });
      saveInventory(nativeProject, inventory);
      const nativeAssumption = persistTestAssumption({
        project: nativeProject,
        input: {
          purpose: 'Attempt a forbidden generated fallback.',
          facts: [
            {
              statement: 'A card exists.',
              status: 'known',
              inputFiles: ['src/Card.jsx'],
              detail: 'Fixture source.',
            },
          ],
          scope: { files: ['src/Card.jsx'], cases: ['card-dark'] },
          rationale: 'Fixture.',
          alternatives: [],
          limitations: [],
        },
        authorKind: 'agent',
        authoredBy: 'fixture-agent',
      });
      expect(
        openEvidenceSurfaceTask({
          project: nativeProject,
          assumptionId: nativeAssumption.id,
          input: definition(),
          goal: 'Do not open implicitly.',
          workspaceRoot,
        }),
      ).toMatchObject({
        ok: false,
        reasons: [expect.stringContaining('known-insufficient')],
      });
      const explicit = openEvidenceSurfaceTask({
        project: nativeProject,
        assumptionId: nativeAssumption.id,
        input: {
          ...definition(),
          nativeSurfaceDisposition: 'known-insufficient',
          rationale:
            'The native E2E surface cannot reach this disposable local route.',
        },
        goal: 'Open only after explicit insufficiency classification.',
        workspaceRoot,
      });
      expect(explicit).toMatchObject({ ok: true });
      if (!explicit.ok) throw new Error(explicit.reasons.join('\n'));
      expect(explicit.task.limitations).toEqual(
        expect.arrayContaining([
          expect.stringContaining('despite known repository-native'),
        ]),
      );
    } finally {
      removeTempDir(nativeRepo);
    }
  });

  test('opens through the stable CLI', () => {
    const file = path.join(repo, 'probe.json');
    fs.writeFileSync(file, JSON.stringify(definition()));
    let stdout = '';
    expect(
      runCli(
        [
          'runtime',
          'probe',
          'open',
          assumption.id,
          'probe.json',
          'Create the exact card-dark evidence surface.',
          '--json',
        ],
        { cwd: repo, writeStdout: (text) => (stdout += text) },
      ),
    ).toBe(0);
    expect(JSON.parse(stdout)).toMatchObject({
      command: 'runtime probe open',
      state: 'open',
      origin: { kind: 'evidence-surface' },
      warnings: [expect.stringContaining('not repository intent')],
    });
  });

  test('rejects inline or arbitrary server execution', () => {
    expect(() =>
      openEvidenceSurfaceTask({
        project,
        assumptionId: assumption.id,
        input: {
          ...definition(),
          server: {
            ...definition().server,
            argv: ['node', '-e', 'require("http").createServer().listen(4173)'],
          },
        },
        goal: 'Reject inline execution.',
        workspaceRoot,
      }),
    ).toThrow('inline evaluation');
    expect(() =>
      openEvidenceSurfaceTask({
        project,
        assumptionId: assumption.id,
        input: {
          ...definition(),
          server: {
            ...definition().server,
            argv: ['sh', '-c', 'node scripts/serve.cjs'],
          },
        },
        goal: 'Reject a shell command.',
        workspaceRoot,
      }),
    ).toThrow('arbitrary executables');
  });

  test('pins a direct server script relative to a nested package root', () => {
    const nestedRepo = createTempRepo({
      'package.json': JSON.stringify({ private: true }),
      'apps/web/package.json': JSON.stringify({
        private: true,
        devDependencies: { playwright: '1.0.0' },
      }),
      'apps/web/scripts/serve.cjs':
        'require("http").createServer().listen(4173);\n',
      'src/Card.jsx': 'export const Card = () => <div>Card</div>;\n',
    });
    try {
      const nestedProject = initializeProject({ repositoryRoot: nestedRepo });
      const inventory = scanRepository({ repositoryRoot: nestedRepo });
      saveInventory(nestedProject, inventory);
      const nestedAssumption = persistTestAssumption({
        project: nestedProject,
        input: {
          purpose: 'Exercise a nested-package probe.',
          facts: [
            {
              statement: 'The card is selected for the nested probe.',
              status: 'known',
              inputFiles: ['src/Card.jsx'],
              detail: 'Fixture source.',
            },
          ],
          scope: { files: ['src/Card.jsx'], cases: ['card-dark'] },
          rationale: 'Fixture.',
          alternatives: [],
          limitations: [],
        },
        authorKind: 'agent',
        authoredBy: 'fixture-agent',
      });
      const nestedDefinition = {
        ...definition(),
        packageRoot: 'apps/web',
        server: {
          ...definition().server,
          inputFiles: ['apps/web/scripts/serve.cjs'],
        },
      };
      expect(
        openEvidenceSurfaceTask({
          project: nestedProject,
          assumptionId: nestedAssumption.id,
          input: nestedDefinition,
          goal: 'Open a nested-package probe.',
          workspaceRoot,
        }),
      ).toMatchObject({ ok: true });
    } finally {
      removeTempDir(nestedRepo);
    }
  });
});
