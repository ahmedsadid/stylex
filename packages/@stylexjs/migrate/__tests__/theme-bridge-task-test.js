import fs from 'fs';
import path from 'path';
import {
  THEME_DECISION_PROTOCOL_VERSION,
  initializeProject,
  loadVerificationCandidate,
  openContextRetry,
  openThemeBridgeTask,
  persistThemeDecisionDraft,
  saveInventory,
  scanRepository,
  submitContextAttempt,
} from '../src/index';
import { runCli } from '../src/cli';
import type { ProjectState } from '../src/index';
import {
  createTempDir,
  createTempRepo,
  readFile,
  removeTempDir,
  writeFiles,
} from './utils/tempRepo';

describe('theme bridge contextual tasks', () => {
  let repo: string;
  let workspaceRoot: string;
  let project: ProjectState;
  let originalProvider: string;

  beforeEach(() => {
    originalProvider = `import {ThemeProvider} from '@emotion/react';
import {darkTheme, lightTheme} from './theme/source';
export const App = ({children, dark}) => {
  const theme = dark ? darkTheme : lightTheme;
  return <main><ThemeProvider theme={theme}>{children}</ThemeProvider></main>;
};
`;
    repo = createTempRepo({
      'src/theme/source.ts': `export const lightTheme = {colors: {foreground: '#111'}};
export const darkTheme = {colors: {foreground: '#eee'}};
`,
      'src/Card.tsx': `import styled from '@emotion/styled';
export const Card = styled.div\`color: \${p => p.theme.colors.foreground};\`;
`,
      'src/App.tsx': originalProvider,
    });
    workspaceRoot = createTempDir('stylex-migrate-theme-bridge-task-');
    project = initializeProject({ repositoryRoot: repo });
    const inventory = scanRepository({ repositoryRoot: repo });
    saveInventory(project, inventory);
  });

  afterEach(() => {
    removeTempDir(workspaceRoot);
    removeTempDir(repo);
  });

  function createDraft(): $FlowFixMe {
    const inventory = scanRepository({ repositoryRoot: repo });
    saveInventory(project, inventory);
    return persistThemeDecisionDraft({
      project,
      draftedBy: 'fixture-agent',
      definition: {
        protocolVersion: THEME_DECISION_PROTOCOL_VERSION,
        inventoryId: inventory.id,
        targetModule: 'src/theme/tokens.stylex.ts',
        varsExport: 'themeVars',
        defaultVariant: 'light',
        variants: [
          {
            name: 'light',
            exportName: 'lightTheme',
            sourceFile: 'src/theme/source.ts',
          },
          {
            name: 'dark',
            exportName: 'darkTheme',
            sourceFile: 'src/theme/source.ts',
          },
        ],
        tokens: [
          {
            sourcePath: 'colors.foreground',
            targetName: 'colorsForeground',
            values: { light: '#111', dark: '#eee' },
            existingCssVariable: null,
          },
        ],
        sourceFiles: ['src/theme/source.ts'],
        consumerFiles: ['src/Card.tsx'],
        bridge: {
          coverageGlobs: ['src/**'],
          boundaryFiles: ['src/App.tsx'],
        },
      },
    });
  }

  test('locks generated bytes, reseeds retry, and freezes complete wiring', () => {
    const draft = createDraft();
    const opened = openThemeBridgeTask({
      project,
      draftId: draft.id,
      goal: 'Apply both generated variants at the existing root host.',
      workspaceRoot,
    });
    if (!opened.ok) throw new Error(opened.reasons.join('\n'));
    expect(opened.task).toMatchObject({
      planId: null,
      origin: {
        kind: 'theme-bridge',
        draftId: draft.id,
        definitionHash: draft.definitionHash,
      },
      scope: {
        allowedPaths: ['src/App.tsx', 'src/theme/tokens.stylex.ts'],
      },
      requiredOutputs: [
        {
          path: 'src/theme/tokens.stylex.ts',
          role: 'generated-theme-module',
          mutable: false,
        },
      ],
    });
    const generated = readFile(
      opened.attempt.workspace.path,
      'src/theme/tokens.stylex.ts',
    );
    expect(generated).toContain('stylex.defineVars');
    fs.writeFileSync(
      path.join(opened.attempt.workspace.path, 'src/theme/tokens.stylex.ts'),
      `${generated}\n// agent mutation\n`,
    );
    expect(
      submitContextAttempt({
        project,
        taskId: opened.task.id,
        proposerKind: 'agent',
        proposerVersion: 'fixture-v1',
      }),
    ).toMatchObject({
      ok: false,
      state: 'needs-replan',
      reasons: [expect.stringContaining('was modified')],
    });

    const retry = openContextRetry({
      project,
      taskId: opened.task.id,
      workspaceRoot,
    });
    if (!retry.ok) throw new Error(retry.reasons.join('\n'));
    expect(
      readFile(retry.attempt.workspace.path, 'src/theme/tokens.stylex.ts'),
    ).toBe(generated);
    writeFiles(retry.attempt.workspace.path, {
      'src/App.tsx': `import {ThemeProvider} from '@emotion/react';
import * as stylex from '@stylexjs/stylex';
import {darkTheme, lightTheme} from './theme/source';
import {darkTheme as darkStylexTheme, lightTheme as lightStylexTheme} from './theme/tokens.stylex';
export const App = ({children, dark}) => {
  const theme = dark ? darkTheme : lightTheme;
  const stylexTheme = dark ? darkStylexTheme : lightStylexTheme;
  return <main {...stylex.props(stylexTheme)}><ThemeProvider theme={theme}>{children}</ThemeProvider></main>;
};
`,
    });
    const submitted = submitContextAttempt({
      project,
      taskId: opened.task.id,
      proposerKind: 'agent',
      proposerName: 'fixture-agent',
      proposerVersion: 'fixture-v1',
    });
    if (!submitted.ok) throw new Error(submitted.reasons.join('\n'));
    const candidate = loadVerificationCandidate(project, submitted.candidateId);
    expect(candidate).toMatchObject({
      classification: 'repeatable-contextual',
      staticEvidence: [
        {
          check: 'theme-bridge-wiring',
          result: 'pass',
          subject: { model: 'theme-bridge-wiring-v2' },
        },
      ],
    });
    expect(candidate?.candidate.decisionArtifactHashes).toEqual([
      draft.definitionHash,
    ]);
    let explained = '';
    expect(
      runCli(['explain', submitted.candidateId, '--json'], {
        cwd: repo,
        writeStdout: (text) => {
          explained += text;
        },
      }),
    ).toBe(0);
    expect(JSON.parse(explained)).toMatchObject({
      detail: {
        decisionStatus: { status: 'bound-input' },
      },
    });
    expect(readFile(repo, 'src/App.tsx')).toBe(originalProvider);
    expect(fs.existsSync(path.join(repo, draft.targetModule))).toBe(false);
  });

  test('rejects a frozen bridge that omits a declared variant', () => {
    const draft = createDraft();
    const opened = openThemeBridgeTask({
      project,
      draftId: draft.id,
      goal: 'Attempt incomplete bridge wiring.',
      workspaceRoot,
    });
    if (!opened.ok) throw new Error(opened.reasons.join('\n'));
    writeFiles(opened.attempt.workspace.path, {
      'src/App.tsx': `import {ThemeProvider} from '@emotion/react';
import * as stylex from '@stylexjs/stylex';
import {darkTheme, lightTheme} from './theme/source';
import {darkTheme as darkStylexTheme} from './theme/tokens.stylex';
export const App = ({children, dark}) => {
  const theme = dark ? darkTheme : lightTheme;
  return <main {...stylex.props(darkStylexTheme)}><ThemeProvider theme={theme}>{children}</ThemeProvider></main>;
};
`,
    });
    expect(
      submitContextAttempt({
        project,
        taskId: opened.task.id,
        proposerKind: 'agent',
        proposerVersion: 'fixture-v1',
      }),
    ).toMatchObject({
      ok: false,
      reasons: [expect.stringContaining('lightTheme')],
    });
  });

  test('opens the bridge workflow through the stable CLI', () => {
    const draft = createDraft();
    let stdout = '';
    const code = runCli(
      [
        'theme',
        'bridge',
        'open',
        draft.id,
        'Integrate both variants at the existing host.',
        '--json',
      ],
      {
        cwd: repo,
        writeStdout: (text) => {
          stdout += text;
        },
      },
    );
    expect(code).toBe(0);
    const output = JSON.parse(stdout);
    expect(output).toMatchObject({
      command: 'theme bridge open',
      state: 'open',
      origin: { kind: 'theme-bridge', draftId: draft.id },
      allowedPaths: ['src/App.tsx', 'src/theme/tokens.stylex.ts'],
      requiredOutputs: [
        {
          path: 'src/theme/tokens.stylex.ts',
          mutable: false,
        },
      ],
    });
    expect(readFile(output.workspace, 'src/theme/tokens.stylex.ts')).toContain(
      'stylex.defineVars',
    );
    expect(
      runCli(['context', 'abandon', output.taskId, '--json'], {
        cwd: repo,
        writeStdout: () => {},
      }),
    ).toBe(0);
    expect(fs.existsSync(output.workspace)).toBe(false);
  });
});
