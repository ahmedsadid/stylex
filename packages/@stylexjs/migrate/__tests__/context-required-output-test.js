import fs from 'fs';
import path from 'path';
import { hashBytes } from '../src/index';
import { assertContextRequiredOutputs } from '../src/context/lifecycle';
import type { ContextRequiredOutput } from '../src/index';
import { createTempDir, removeTempDir } from './utils/tempRepo';

describe('contextual required outputs', () => {
  let root: string;

  beforeEach(() => {
    root = createTempDir('stylex-migrate-required-output-');
  });

  afterEach(() => {
    removeTempDir(root);
  });

  test('accepts only the exact generated bytes', () => {
    const file = 'src/theme.stylex.ts';
    const contents = Buffer.from('export const theme = {};\n');
    fs.mkdirSync(path.join(root, 'src'));
    fs.writeFileSync(path.join(root, file), contents);
    const required: $ReadOnlyArray<ContextRequiredOutput> = [
      {
        path: file,
        targetHash: hashBytes(contents),
        role: 'generated-theme-module',
        mutable: false,
      },
    ];
    expect(() => assertContextRequiredOutputs(root, required)).not.toThrow();
    fs.writeFileSync(path.join(root, file), 'export const theme = changed;\n');
    expect(() => assertContextRequiredOutputs(root, required)).toThrow(
      'was modified after the kernel generated it',
    );
  });

  test('refuses missing and symlinked outputs', () => {
    const contents = Buffer.from('theme');
    const required: $ReadOnlyArray<ContextRequiredOutput> = [
      {
        path: 'theme.stylex.ts',
        targetHash: hashBytes(contents),
        role: 'generated-theme-module',
        mutable: false,
      },
    ];
    expect(() => assertContextRequiredOutputs(root, required)).toThrow(
      'missing or unreadable',
    );
    fs.writeFileSync(path.join(root, 'outside'), contents);
    fs.symlinkSync(
      path.join(root, 'outside'),
      path.join(root, 'theme.stylex.ts'),
    );
    expect(() => assertContextRequiredOutputs(root, required)).toThrow(
      'symlink',
    );
  });

  test('refuses a required output beneath a symlinked parent', () => {
    const outside = createTempDir('stylex-migrate-required-outside-');
    try {
      fs.symlinkSync(outside, path.join(root, 'src'));
      const required: $ReadOnlyArray<ContextRequiredOutput> = [
        {
          path: 'src/theme.stylex.ts',
          targetHash: hashBytes(Buffer.from('theme')),
          role: 'generated-theme-module',
          mutable: false,
        },
      ];
      expect(() => assertContextRequiredOutputs(root, required)).toThrow(
        /unsafe contextual required output parent/i,
      );
    } finally {
      removeTempDir(outside);
    }
  });
});
